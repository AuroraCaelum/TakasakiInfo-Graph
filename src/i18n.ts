export const DICTS: Record<UiLang, Dict> = { ko, en, ja };

export function detectUiLang(): UiLang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.toLowerCase().slice(0, 2);
    if (base === "ko" || base === "ja" || base === "en") return base;
  }
  return "en";
}
